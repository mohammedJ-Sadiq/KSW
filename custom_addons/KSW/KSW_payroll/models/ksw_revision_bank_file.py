import re

from markupsafe import Markup

from odoo import api, fields, models, _
from odoo.exceptions import UserError

from .ksw_payslip_revision_request import ACC_GROUP


class KswRevisionBankFile(models.Model):
    """One bank transfer file for several salary revisions.

    Before this, every revision paid by bank produced its own Excel + TXT at
    Confirm & Pay, so ten approved revisions meant ten uploads to the bank.
    Now Confirm & Pay leaves a bank request in ``pending_bank_file``, and
    accounting picks which of the pending requests go into a file.  The ones
    picked are marked paid against this record; the rest stay pending for the
    next file.

    The files are kept here and never on the requests: each one carries every
    included employee's account and amount, and the request's Supporting
    Documents are visible to the employee who filed it.
    """

    _name = 'ksw.revision.bank.file'
    _description = 'Salary Revision Bank File'
    _inherit = ['mail.thread']
    _order = 'id desc'

    name = fields.Char(
        string='Reference', required=True, copy=False, readonly=True,
        default=lambda self: _('New'), index=True,
    )
    state = fields.Selection(
        [('draft', 'Draft'), ('done', 'Generated')],
        string='Status', default='draft', required=True, readonly=True,
        copy=False, tracking=True,
    )
    company_id = fields.Many2one(
        'res.company', string='Company', readonly=True,
        default=lambda self: self.env.company,
    )
    value_date = fields.Date(
        string='Value Date', required=True,
        default=fields.Date.context_today,
        help='Payment value date written into the TXT file header, and the '
             'payment date stamped on every request in the file.',
    )
    request_ids = fields.Many2many(
        'ksw.payslip.revision.request',
        'ksw_revision_bank_file_request_rel', 'bank_file_id', 'request_id',
        string='Revision Requests', copy=False,
        domain="[('state', '=', 'pending_bank_file')]",
        help='The approved bank-transfer revisions this file pays. Remove '
             'any that should wait for a later file.',
    )
    request_count = fields.Integer(compute='_compute_totals')
    total_amount = fields.Float(
        string='Total', compute='_compute_totals', digits=(16, 2))

    payslip_run_id = fields.Many2one(
        'hr.payslip.run', string='Payment Batch', readonly=True, copy=False,
        help='The batch holding the revision payslips this file was '
             'generated from.',
    )
    attachment_ids = fields.Many2many(
        'ir.attachment', 'ksw_revision_bank_file_attachment_rel',
        'bank_file_id', 'attachment_id', string='Bank Files',
        readonly=True, copy=False,
    )
    generated_by_id = fields.Many2one(
        'res.users', string='Generated By', readonly=True, copy=False)
    generated_date = fields.Datetime(
        string='Generated On', readonly=True, copy=False)

    @api.depends('request_ids')
    def _compute_totals(self):
        for rec in self:
            rec.request_count = len(rec.request_ids)
            rec.total_amount = sum(rec.request_ids.mapped('difference_amount'))

    @api.model
    def default_get(self, fields_list):
        """Start from the rows accounting selected in the request list, or
        from everything pending when the file is opened from the menu."""
        res = super().default_get(fields_list)
        if 'request_ids' in fields_list and not res.get('request_ids'):
            Request = self.env['ksw.payslip.revision.request']
            ctx = self.env.context
            if ctx.get('active_model') == Request._name and ctx.get('active_ids'):
                pending = Request.browse(ctx['active_ids']).filtered(
                    lambda r: r.state == 'pending_bank_file')
            else:
                pending = Request.search([('state', '=', 'pending_bank_file')])
            res['request_ids'] = [(6, 0, pending.ids)]
        return res

    @api.model_create_multi
    def create(self, vals_list):
        self._check_accounting()
        Seq = self.env['ir.sequence'].sudo()
        for vals in vals_list:
            if vals.get('name', _('New')) == _('New'):
                vals['name'] = Seq.next_by_code(self._name) or _('New')
        return super().create(vals_list)

    def write(self, vals):
        if not self.env.su:
            self._check_accounting()
            if self.filtered(lambda r: r.state != 'draft') and (
                    set(vals) & {'request_ids', 'value_date', 'state'}):
                raise UserError(_(
                    'A generated bank file cannot be changed: it is what was '
                    'sent to the bank.'))
        return super().write(vals)

    def unlink(self):
        if not self.env.su and self.filtered(lambda r: r.state != 'draft'):
            raise UserError(_(
                'A generated bank file cannot be deleted: the requests in it '
                'are recorded as paid by it.'))
        return super().unlink()

    @api.model
    def _check_accounting(self):
        if not self.env.su and not self.env.user.has_group(ACC_GROUP):
            raise UserError(_(
                'Only the accounting team may prepare a revision bank file.'))

    # ------------------------------------------------------------------

    def action_generate(self):
        """Produce one Excel and one TXT for every request in the file and
        mark each of them paid.

        Everything happens in one transaction: if the exporter refuses any
        employee, nothing is marked paid and no file is kept.
        """
        self.ensure_one()
        self._check_accounting()
        if self.state != 'draft':
            raise UserError(_('This bank file has already been generated.'))
        requests = self.request_ids.sudo()
        if not requests:
            raise UserError(_(
                'Add at least one revision request pending a bank file.'))
        stale = requests.filtered(
            lambda r: r.state != 'pending_bank_file'
            or r.payment_method != 'bank' or r.bank_file_id)
        if stale:
            raise UserError(_(
                'These requests are no longer waiting for a bank file — '
                'another file may already have paid them. Remove them and '
                'generate again:\n%(rows)s',
                rows='\n'.join('• %s — %s' % (r.name, r.employee_id.name)
                               for r in stale)))
        slips = requests.mapped('revision_payslip_id')
        unconfirmed = requests.filtered(
            lambda r: r.revision_payslip_id.state != 'done')
        if unconfirmed or len(slips) != len(requests):
            raise UserError(_(
                'These requests have no confirmed revision payslip:\n%(rows)s',
                rows='\n'.join('• %s — %s' % (r.name, r.employee_id.name)
                               for r in unconfirmed)))

        run = self._make_payment_batch(slips)
        attachments = self.env['ir.attachment']
        for mode in ('all_excel', 'all_txt'):
            try:
                attachments |= self._export(run, mode)
            except UserError as exc:
                raise UserError(_(
                    'The bank file was NOT generated and no request was '
                    'marked paid.\n\nReason: %(reason)s\n\nRemove the '
                    'request(s) concerned or fix their bank account, then '
                    'generate again.',
                    reason=exc.args[0] if exc.args else str(exc),
                )) from exc

        self.sudo().write({
            'state': 'done',
            'payslip_run_id': run.id,
            'attachment_ids': [(6, 0, attachments.ids)],
            'generated_by_id': self.env.uid,
            'generated_date': fields.Datetime.now(),
        })
        requests._mark_paid_by_bank_file(self)
        rows = Markup('').join(
            Markup('<li>%(ref)s — %(emp)s: %(amt).2f SAR</li>') % {
                'ref': r.name, 'emp': r.employee_id.name,
                'amt': r.difference_amount}
            for r in requests)
        self.sudo().message_post(
            body=Markup(
                '<strong>🏦 Bank file generated</strong><br/>'
                '<b>By:</b> %(user)s<br/>'
                '<b>Total:</b> %(total).2f SAR<ul>%(rows)s</ul>') % {
                    'user': self.env.user.name,
                    'total': self.total_amount,
                    'rows': rows},
            subtype_xmlid='mail.mt_note',
        )
        return True

    def _make_payment_batch(self, slips):
        """The ``hr.payslip.run`` the exporter needs, holding exactly these
        revision payslips.  Same shape as the single-request batch the
        request used to build (``_ensure_payment_batch``)."""
        self.ensure_one()
        slips = slips.sudo()
        run = self.env['hr.payslip.run'].sudo().create({
            # No slashes or em dashes: the name becomes the file name via
            # the export wizard's _batch_label().
            'name': _('Salary Revisions %(ref)s',
                      ref=self.name.replace('/', '-')),
            'date_start': min(slips.mapped('date_from')),
            'date_end': max(slips.mapped('date_to')),
        })
        old_runs = slips.mapped('payslip_run_id')
        slips.write({'payslip_run_id': run.id})
        if old_runs:
            old_runs._refresh_bank_totals()
        # A straight write, never done_payslip_run(): the slips are already
        # done, and re-confirming recomputes them (pitfall #49).
        run.write({'state': 'done'})
        run._refresh_bank_totals()
        return run

    def _export(self, run, mode):
        """Run the batch exporter and re-home its attachment here, so the
        accounting user can download it (the batch would 403 for them)."""
        wizard = self.env['ksw.bank.file.export.wizard'].sudo().create({
            'payslip_run_id': run.id,
            'export_mode': mode,
            'value_date': self.value_date,
        })
        action = wizard.action_export() or {}
        match = re.search(r'/web/content/(\d+)', action.get('url') or '')
        if not match:
            raise UserError(_('The exporter produced no file.'))
        attachment = self.env['ir.attachment'].sudo().browse(
            int(match.group(1)))
        attachment.write({'res_model': self._name, 'res_id': self.id})
        return attachment
